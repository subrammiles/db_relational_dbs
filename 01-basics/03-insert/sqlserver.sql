-- 03 · INSERT in SQL Server (T-SQL)

DROP TABLE IF EXISTS users;
CREATE TABLE users (
    user_id  INT IDENTITY(1,1) PRIMARY KEY,
    phone    VARCHAR(15) NOT NULL,
    email    VARCHAR(60) NOT NULL
);

-- One row
INSERT INTO users (phone, email) VALUES ('123456', 'test@gmail.com');
SELECT SCOPE_IDENTITY() AS new_id;          -- id generated by THIS statement in THIS scope

-- Several rows (max 1000 rows per VALUES list)
INSERT INTO users (phone, email) VALUES
    ('987654', 'test2@gmail.com'),
    ('555666', 'test3@gmail.com');

-- OUTPUT returns the inserted rows (like RETURNING)
INSERT INTO users (phone, email)
OUTPUT inserted.user_id, inserted.email
VALUES ('111222', 'new@gmail.com');

-- INSERT ... SELECT
INSERT INTO users (phone, email)
SELECT '000', email FROM customers WHERE country = 'UK' AND email IS NOT NULL;

-- Supplying an explicit value for an IDENTITY column needs IDENTITY_INSERT
SET IDENTITY_INSERT users ON;
INSERT INTO users (user_id, phone, email) VALUES (100, '999', 'manual@gmail.com');
SET IDENTITY_INSERT users OFF;

SELECT * FROM users ORDER BY user_id;

DROP TABLE users;
